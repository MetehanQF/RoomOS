#!/usr/bin/env bash
# Regenerate core/requirements.lock from the Python environment of a built RoomOS Core image.
# The lock pins every runtime distribution except roomos-core itself and pip, with the sha256 of
# the exact wheel that was installed.
set -euo pipefail

image=${1:-}
if [[ -z "$image" ]]; then
  echo "usage: $0 <roomos-core-image>" >&2
  exit 2
fi

repo_dir=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
lock_file="$repo_dir/core/requirements.lock"

image_id=$(docker image inspect --format '{{.Id}}' "$image")
revision=$(docker image inspect --format '{{index .Config.Labels "org.opencontainers.image.revision"}}' "$image")

body=$(docker run --rm -i --network none --entrypoint python "$image" - <<'PY'
import json
import re
import sys
from importlib.metadata import distributions

EXCLUDED = {"pip", "roomos-core", "setuptools", "wheel"}
entries = {}
for dist in distributions():
    name = re.sub(r"[-_.]+", "-", dist.metadata["Name"]).lower()
    if name in EXCLUDED:
        continue
    direct_url = dist.read_text("direct_url.json")
    if not direct_url:
        sys.exit(f"{name} has no direct_url.json; cannot recover its wheel hash")
    info = json.loads(direct_url).get("archive_info", {})
    digest = info.get("hashes", {}).get("sha256") or info.get("hash", "").removeprefix("sha256=")
    if not re.fullmatch(r"[0-9a-f]{64}", digest):
        sys.exit(f"{name} has no sha256 wheel hash")
    entries[name] = f"{name}=={dist.version} \\\n    --hash=sha256:{digest}"
print("\n".join(entries[name] for name in sorted(entries)))
PY
)

{
  echo "# RoomOS Core runtime lock. Generated by scripts/lock-core-deps.sh; do not edit by hand."
  echo "# Source image: $image ($image_id)"
  echo "# Source revision: $revision"
  echo "# Platform: linux/$(docker image inspect --format '{{.Architecture}}' "$image"), CPython 3.12"
  echo "$body"
} >"$lock_file"
python3 "$repo_dir/scripts/lock_add_platform_hashes.py" "$lock_file"

echo "wrote $lock_file"
